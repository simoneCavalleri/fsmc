#pragma once

#include <cctype>
#include <chrono>
#include <regex>
#include <sstream>
#include <string>
#include <string_view>
#include <unordered_map>
#include <unordered_set>

#include "fsm/ir/fsm_ir.hpp"
#include "fsm/middleend/analysis/model_checker.hpp"

namespace fsm::middleend::analysis {

class CounterexampleGTestExporter {
  public:
    static std::string export_gtest(const ::fsm::ir::FsmIr& model, const ModelCheckResult& result,
                                    std::string_view header_include = "",
                                    std::string_view target_namespace = "fsm_generated") {
        std::ostringstream out;
        std::string hdr = header_include.empty() ? (model.name + "_fsm.hpp") : std::string(header_include);
        out << "// Auto-generated by fsmc --export-cex-gtest\n"
            << "#include <chrono>\n"
            << "#include <gtest/gtest.h>\n"
            << "#include \"" << hdr << "\"\n\n";
        if (!target_namespace.empty()) {
            out << "using namespace " << target_namespace << ";\n\n";
        }

        std::string test_name = result.property_name.empty() ? "Counterexample" : result.property_name;
        for (char& c : test_name) {
            if (std::isalnum(static_cast<unsigned char>(c)) == 0 && c != '_') {
                c = '_';
            }
        }

        std::unordered_set<std::string> in_port_names;
        for (const auto& p : model.ports) {
            if (p.is_in()) {
                in_port_names.insert(p.name);
            }
        }
        const bool has_in_ports = !in_port_names.empty();

        out << "TEST(" << model.name << "CounterexampleTest, Reproduces_" << test_name << ") {\n"
            << "    // Violated property: " << result.property_formula << "\n"
            << "    " << model.name << " sm;\n";
        if (has_in_ports) {
            out << "    " << model.name << "::in_ports_type in{};\n"
                << "    " << model.name << "::out_ports_type out{};\n";
        }

        auto resolve_guard_expr = [&](const std::string& raw_guard) -> std::string {
            std::string expr = raw_guard;
            if (const auto* g = model.find_guard(raw_guard)) {
                if (g->raw_expression.has_value() && !g->raw_expression->empty()) {
                    return *g->raw_expression;
                }
            }
            // Expand symbolic guard identifiers inside compound guard expressions (e.g. `ambient_gt_20 && delta_gt_5`)
            std::string expanded;
            expanded.reserve(expr.size() + 32U);
            std::size_t i = 0U;
            while (i < expr.size()) {
                const unsigned char ch = static_cast<unsigned char>(expr[i]);
                if (std::isalpha(ch) != 0 || expr[i] == '_') {
                    const std::size_t start = i;
                    while (i < expr.size() &&
                           (std::isalnum(static_cast<unsigned char>(expr[i])) != 0 || expr[i] == '_')) {
                        ++i;
                    }
                    const std::string tok = expr.substr(start, i - start);
                    if (const auto* g = model.find_guard(tok); g != nullptr && g->raw_expression.has_value() &&
                                                               !g->raw_expression->empty() &&
                                                               *g->raw_expression != tok) {
                        expanded += "(" + *g->raw_expression + ")";
                    } else {
                        expanded += tok;
                    }
                } else {
                    expanded.push_back(expr[i++]);
                }
            }
            return expanded;
        };

        auto emit_witness_assignments = [&](std::ostream& dst, const std::string& raw_guard,
                                            const std::unordered_set<std::string>& allowed_names,
                                            const std::string& lhs_prefix, const std::string& indent) {
            if (allowed_names.empty() || raw_guard.empty()) {
                return;
            }
            const std::string expr = resolve_guard_expr(raw_guard);
            static const std::regex cmp_re(
                R"((?:(?:in|ev|event)\.)?([A-Za-z_][A-Za-z0-9_]*)\s*(>=|<=|==|!=|>|<)\s*(-?[0-9]+(?:\.[0-9]+)?|true|false))");
            auto begin = std::sregex_iterator(expr.begin(), expr.end(), cmp_re);
            auto end = std::sregex_iterator();
            for (auto it = begin; it != end; ++it) {
                const std::string lhs = (*it)[1].str();
                const std::string op = (*it)[2].str();
                const std::string rhs = (*it)[3].str();
                if (allowed_names.count(lhs) == 0U) {
                    continue;
                }
                if (rhs == "true" || rhs == "false") {
                    bool val = (rhs == "true");
                    if (op == "!=") {
                        val = !val;
                    }
                    dst << indent << lhs_prefix << lhs << " = " << (val ? "true" : "false") << ";\n";
                } else {
                    const bool is_float = (rhs.find('.') != std::string::npos);
                    if (op == "==" || op == ">=" || op == "<=") {
                        dst << indent << lhs_prefix << lhs << " = " << rhs << ";\n";
                    } else if (op == ">" || op == "!=") {
                        dst << indent << lhs_prefix << lhs << " = " << rhs << (is_float ? " + 1.0;\n" : " + 1;\n");
                    } else if (op == "<") {
                        dst << indent << lhs_prefix << lhs << " = " << rhs << (is_float ? " - 1.0;\n" : " - 1;\n");
                    }
                }
            }
        };

        // Map TimeTrigger event names (e.g. "after_100ms") to duration in milliseconds
        std::unordered_map<std::string, uint64_t> timer_durations_ms;
        for (const auto& tr : model.transitions) {
            if (const auto* tt = std::get_if<::fsm::ir::TimeTrigger>(&tr.trigger)) {
                const uint64_t dur = tt->duration_ms > 0 ? tt->duration_ms : tt->duration_in_ms();
                const std::string tname = tr.get_trigger_name();
                if (!tname.empty() && dur > 0U) {
                    timer_durations_ms[tname] = dur;
                }
            }
        }

        std::string final_state;
        for (const auto& step : result.counterexample_trace) {
            if (!step.state_name.empty()) {
                final_state = step.state_name;
            }
            if (!step.guard_condition.empty()) {
                emit_witness_assignments(out, step.guard_condition, in_port_names, "in.", "    ");
            }
            if (step.event_name.empty() || step.event_name == "enter_composite") {
                continue;
            }
            if (step.event_name == "anonymous_event" || step.event_name == "completion_event") {
                if (has_in_ports) {
                    out << "    sm.step(in, out);\n";
                } else {
                    out << "    sm.step();\n";
                }
                continue;
            }
            // Check if this step corresponds to a TimeTrigger (e.g. after_100ms / every_50ms)
            uint64_t timer_ms = 0U;
            if (auto tit = timer_durations_ms.find(step.event_name); tit != timer_durations_ms.end()) {
                timer_ms = tit->second;
            } else {
                static const std::regex time_ev_re(R"(^(?:after|every)_([0-9]+)ms$)");
                std::smatch tm;
                if (std::regex_match(step.event_name, tm, time_ev_re)) {
                    timer_ms = std::stoull(tm[1].str());
                }
            }
            if (timer_ms > 0U) {
                if (has_in_ports) {
                    out << "    sm.step(std::chrono::milliseconds(" << timer_ms << "), in, out);\n";
                } else {
                    out << "    sm.step(std::chrono::milliseconds(" << timer_ms << "));\n";
                }
                continue;
            }
            const auto* sig = model.find_signal(step.event_name);
            std::string ev_witnesses;
            if (sig != nullptr && !sig->attributes.empty() && !step.guard_condition.empty()) {
                std::unordered_set<std::string> ev_attrs;
                for (const auto& attr : sig->attributes) {
                    ev_attrs.insert(attr.name);
                }
                std::ostringstream ev_ss;
                emit_witness_assignments(ev_ss, step.guard_condition, ev_attrs, "ev.", "        ");
                ev_witnesses = ev_ss.str();
            }
            if (!ev_witnesses.empty()) {
                out << "    {\n";
                out << "        " << step.event_name << " ev{};\n";
                out << ev_witnesses;
                if (has_in_ports) {
                    out << "        sm.dispatch(ev, in, out);\n";
                } else {
                    out << "        sm.dispatch(ev);\n";
                }
                out << "    }\n";
            } else if (has_in_ports) {
                out << "    sm.dispatch(" << step.event_name << "{}, in, out);\n";
            } else {
                out << "    sm.dispatch(" << step.event_name << "{});\n";
            }
        }
        if (!final_state.empty()) {
            out << "    EXPECT_TRUE(sm.is_in<" << final_state << ">());\n";
        }
        out << "}\n";
        return out.str();
    }
};

}  // namespace fsm::middleend::analysis

namespace fsm::tools {
using ::fsm::middleend::analysis::CounterexampleGTestExporter;
}  // namespace fsm::tools
